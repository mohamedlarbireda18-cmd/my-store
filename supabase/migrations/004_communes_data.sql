-- Helper function to get wilaya ID by code
CREATE OR REPLACE FUNCTION get_wilaya_id(wilaya_code VARCHAR)
RETURNS UUID AS $$
DECLARE
    wilaya_id UUID;
BEGIN
    SELECT id INTO wilaya_id FROM wilayas WHERE code = wilaya_code;
    RETURN wilaya_id;
END;
$$ LANGUAGE plpgsql;

